/*
 * Host test for QEMU's `-display android` wire format and buffer ring.
 *
 * The code under test is the exact header that ships inside
 * emu/qemu/patches/qemu/0003-ui-add-android-ahb-backend.patch (`ui/android-proto.h`), extracted
 * by run.sh into a scratch directory. It has no QEMU and no Android dependencies on purpose, so
 * the two things that break frame transport silently — the byte layout and the ring bookkeeping —
 * are exercised here instead of only on a device.
 *
 * `golden-messages.txt` is the contract with crates/carbon-emu/src/frame_proto.rs: this test
 * proves the C producer emits those bytes, and the Rust test proves the reader accepts them.
 * Regenerate with `run.sh --emit` only for an intentional protocol change.
 */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "ui/android-proto.h"

static int failures;
static int checks;

#define CHECK(cond)                                                              \
    do {                                                                         \
        checks++;                                                                \
        if (!(cond)) {                                                           \
            fprintf(stderr, "FAIL %s:%d: %s\n", __FILE__, __LINE__, #cond);      \
            failures++;                                                          \
        }                                                                        \
    } while (0)

#define CHECK_EQ_U32(got, want)                                                  \
    do {                                                                         \
        uint64_t g_ = (uint64_t)(got), w_ = (uint64_t)(want);                    \
        checks++;                                                                \
        if (g_ != w_) {                                                          \
            fprintf(stderr, "FAIL %s:%d: %s = %llu, want %llu\n", __FILE__,      \
                    __LINE__, #got, (unsigned long long)g_,                      \
                    (unsigned long long)w_);                                     \
            failures++;                                                          \
        }                                                                        \
    } while (0)

/* Builds every message this backend can produce, with fixed inputs. */
typedef struct Golden {
    const char *name;
    size_t len;
    uint8_t bytes[64];
} Golden;

static size_t build_goldens(Golden *out)
{
    size_t n = 0;

    out[n].name = "hello";
    out[n].len = android_proto_hello(out[n].bytes);
    n++;

    out[n].name = "mode_640x480";
    out[n].len = android_proto_mode(out[n].bytes, 640, 480,
                                    ANDROID_AHB_FORMAT_R8G8B8A8_UNORM);
    n++;

    out[n].name = "mode_1080x2400";
    out[n].len = android_proto_mode(out[n].bytes, 1080, 2400,
                                    ANDROID_AHB_FORMAT_R8G8B8A8_UNORM);
    n++;

    out[n].name = "frame_seq1";
    out[n].len = android_proto_frame(out[n].bytes, 1, 640, 480,
                                     ANDROID_AHB_FORMAT_R8G8B8A8_UNORM,
                                     ANDROID_FRAME_USAGE, false);
    n++;

    out[n].name = "frame_seq3_with_fence";
    out[n].len = android_proto_frame(out[n].bytes, 3, 1080, 2400,
                                     ANDROID_AHB_FORMAT_R8G8B8A8_UNORM,
                                     ANDROID_FRAME_USAGE, true);
    n++;

    out[n].name = "cursor_visible";
    out[n].len = android_proto_cursor(out[n].bytes, 12, 34, true);
    n++;

    out[n].name = "cursor_hidden";
    out[n].len = android_proto_cursor(out[n].bytes, 0, 0, false);
    n++;

    return n;
}

static char *to_hex(const uint8_t *bytes, size_t len)
{
    static char hex[256];
    size_t i;

    if (len * 2 + 1 > sizeof(hex)) {
        return NULL;
    }
    for (i = 0; i < len; i++) {
        snprintf(hex + i * 2, 3, "%02x", bytes[i]);
    }
    hex[len * 2] = '\0';
    return hex;
}

static int emit_golden(const char *path, const Golden *golden, size_t count)
{
    FILE *file = fopen(path, "w");
    size_t i;

    if (!file) {
        perror(path);
        return 1;
    }
    fprintf(file, "# Generated by qualification/emu/frame-proto/run.sh --emit.\n");
    fprintf(file, "# Consumed by this test (producer side) and by the\n");
    fprintf(file, "# crates/carbon-emu frame_proto golden test (reader side).\n");
    for (i = 0; i < count; i++) {
        fprintf(file, "%s %s\n", golden[i].name, to_hex(golden[i].bytes, golden[i].len));
    }
    fclose(file);
    printf("wrote %zu golden messages to %s\n", count, path);
    return 0;
}

static void check_golden_file(const char *path, const Golden *golden, size_t count)
{
    FILE *file = fopen(path, "r");
    char line[512];
    size_t seen = 0;

    CHECK(file != NULL);
    if (!file) {
        return;
    }
    while (fgets(line, sizeof(line), file)) {
        char *space;
        size_t i;
        int matched = 0;

        if (line[0] == '#' || line[0] == '\n') {
            continue;
        }
        space = strchr(line, ' ');
        CHECK(space != NULL);
        if (!space) {
            continue;
        }
        *space = '\0';
        (space + 1)[strcspn(space + 1, "\n")] = '\0';

        for (i = 0; i < count; i++) {
            if (strcmp(golden[i].name, line) != 0) {
                continue;
            }
            matched = 1;
            seen++;
            CHECK_EQ_U32(strlen(space + 1) / 2, golden[i].len);
            CHECK(strcmp(to_hex(golden[i].bytes, golden[i].len), space + 1) == 0);
            if (strcmp(to_hex(golden[i].bytes, golden[i].len), space + 1) != 0) {
                fprintf(stderr, "  message %s: C produced %s\n  golden file has %s\n",
                        line, to_hex(golden[i].bytes, golden[i].len), space + 1);
            }
        }
        CHECK(matched);
        if (!matched) {
            fprintf(stderr, "  %s is in the golden file but this backend cannot produce it\n",
                    line);
        }
    }
    fclose(file);
    /* Every message the backend can produce must be pinned, or the Rust reader may not know it. */
    CHECK_EQ_U32(seen, count);
}

static void check_headers(const Golden *golden, size_t count)
{
    size_t i;

    for (i = 0; i < count; i++) {
        const uint8_t *b = golden[i].bytes;
        size_t len = golden[i].len;

        CHECK(len >= ANDROID_PROTO_HEADER_BYTES);
        CHECK_EQ_U32(android_get_u32(b), ANDROID_PROTO_MAGIC);
        CHECK_EQ_U32(android_get_u16(b + 4), ANDROID_PROTO_VERSION);
        CHECK_EQ_U32(len - ANDROID_PROTO_HEADER_BYTES, android_get_u32(b + 8));
        CHECK(len <= ANDROID_PROTO_HEADER_BYTES + ANDROID_PROTO_MAX_PAYLOAD);
    }
}

static void encode_release(uint8_t *out, uint32_t seq)
{
    uint8_t *payload = out + ANDROID_PROTO_HEADER_BYTES;

    android_put_u32(payload, seq);
    android_proto_header(out, ANDROID_MSG_RELEASE, ANDROID_RELEASE_BYTES);
}

static void encode_resize(uint8_t *out, uint32_t width, uint32_t height, uint32_t dpi)
{
    uint8_t *payload = out + ANDROID_PROTO_HEADER_BYTES;

    android_put_u32(payload, width);
    android_put_u32(payload + 4, height);
    android_put_u32(payload + 8, dpi);
    android_proto_header(out, ANDROID_MSG_RESIZE, ANDROID_RESIZE_BYTES);
}

static void check_reader(void)
{
    uint8_t message[ANDROID_PROTO_HEADER_BYTES + ANDROID_RESIZE_BYTES];
    const size_t release_len = ANDROID_PROTO_HEADER_BYTES + ANDROID_RELEASE_BYTES;
    const size_t resize_len = ANDROID_PROTO_HEADER_BYTES + ANDROID_RESIZE_BYTES;
    uint32_t seq = 0, width = 0, height = 0, dpi = 0;

    encode_release(message, 7);
    CHECK(android_proto_decode_release(message, release_len, &seq));
    CHECK_EQ_U32(seq, 7);

    /* seq 0 can never be a live buffer. */
    encode_release(message, 0);
    CHECK(!android_proto_decode_release(message, release_len, &seq));

    /* A FRAME arriving on the app -> QEMU direction is not a RELEASE. */
    android_proto_frame(message, 1, 10, 10, 1, ANDROID_FRAME_USAGE, false);
    CHECK(!android_proto_decode_release(message, ANDROID_PROTO_HEADER_BYTES + ANDROID_FRAME_BYTES,
                                       &seq));

    /* Truncated, over-long, bad magic, wrong version, wrong payload length, extra trailing byte. */
    encode_release(message, 9);
    CHECK(!android_proto_decode_release(message, release_len - 1, &seq));
    message[0] = 0x00;
    CHECK(!android_proto_decode_release(message, release_len, &seq));
    message[0] = 0x46;
    message[4] = 2;
    CHECK(!android_proto_decode_release(message, release_len, &seq));
    message[4] = 1;
    message[8] = 8;
    CHECK(!android_proto_decode_release(message, release_len, &seq));
    message[8] = 4;

    encode_resize(message, 1080, 2400, 440);
    CHECK(android_proto_decode_resize(message, resize_len, &width, &height, &dpi));
    CHECK_EQ_U32(width, 1080);
    CHECK_EQ_U32(height, 2400);
    CHECK_EQ_U32(dpi, 440);

    encode_resize(message, 0, 2400, 440);
    CHECK(!android_proto_decode_resize(message, resize_len, &width, &height, &dpi));
    encode_resize(message, 1080, 0, 440);
    CHECK(!android_proto_decode_resize(message, resize_len, &width, &height, &dpi));
    encode_resize(message, ANDROID_PROTO_MAX_DIMENSION + 1, 2400, 440);
    CHECK(!android_proto_decode_resize(message, resize_len, &width, &height, &dpi));
    encode_resize(message, 1080, 2400, 0);
    CHECK(!android_proto_decode_resize(message, resize_len, &width, &height, &dpi));
    encode_resize(message, 1080, 2400, 10001);
    CHECK(!android_proto_decode_resize(message, resize_len, &width, &height, &dpi));
    CHECK(!android_proto_decode_resize(NULL, resize_len, &width, &height, &dpi));
}

static void check_ring(void)
{
    AndroidFrameRing ring;
    uint32_t index = 99, seq = 0;
    uint32_t first, second;
    int i;

    android_ring_init(&ring);
    CHECK_EQ_U32(android_ring_inflight(&ring), 0);

    /* Three frames fit; the fourth is dropped rather than blocking a vCPU. */
    for (i = 0; i < ANDROID_RING_SLOTS; i++) {
        CHECK(android_ring_acquire(&ring, &index, &seq));
        CHECK_EQ_U32(index, (uint32_t)i);
        CHECK(seq != 0);
        if (i == 0) {
            first = seq;
        }
        if (i == 1) {
            second = seq;
        }
    }
    CHECK_EQ_U32(android_ring_inflight(&ring), ANDROID_RING_SLOTS);
    CHECK(!android_ring_acquire(&ring, &index, &seq));

    /* An unknown or already-freed sequence is refused. */
    CHECK(!android_ring_release(&ring, 12345));
    CHECK(android_ring_release(&ring, first));
    CHECK(!android_ring_release(&ring, first));
    CHECK_EQ_U32(android_ring_inflight(&ring), ANDROID_RING_SLOTS - 1);

    /* The freed slot is reused, and the sequence keeps increasing. */
    CHECK(android_ring_acquire(&ring, &index, &seq));
    CHECK_EQ_U32(index, 0);
    CHECK(seq != first && seq != second);

    /* A mode change invalidates every slot; late releases are harmless. */
    android_ring_reset(&ring);
    CHECK_EQ_U32(android_ring_inflight(&ring), 0);
    CHECK(!android_ring_release(&ring, second));
    CHECK(android_ring_acquire(&ring, &index, &seq));
    CHECK(seq != 0);

    /* Sequences wrap without ever producing the reserved 0. */
    android_ring_reset(&ring);
    ring.next_seq = UINT32_MAX;
    CHECK(android_ring_acquire(&ring, &index, &seq));
    CHECK_EQ_U32(seq, UINT32_MAX);
    CHECK(android_ring_release(&ring, seq));
    CHECK(android_ring_acquire(&ring, &index, &seq));
    CHECK_EQ_U32(seq, 1);
}

int main(int argc, char **argv)
{
    Golden golden[16];
    size_t count = build_goldens(golden);
    const char *path = argc > 1 ? argv[1] : "golden-messages.txt";
    const char *emit = getenv("CARBON_EMU_EMIT_GOLDEN");

    if (emit) {
        return emit_golden(emit, golden, count);
    }

    check_headers(golden, count);
    check_golden_file(path, golden, count);
    check_reader();
    check_ring();

    if (failures) {
        fprintf(stderr, "android-proto: %d of %d checks failed\n", failures, checks);
        return 1;
    }
    printf("android-proto: %d checks passed\n", checks);
    return 0;
}
